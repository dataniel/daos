test_that("scope filters keep original keys, navigate matches and retain hidden flags", {
  skip_if_not_installed("shiny")
  skip_if_not_installed("plotly")
  d <- data.frame(t = rep(1:12, 3), y = 1:36, group = rep(c("a", "b", "c"), each = 12))
  p <- screen_ts_prepare(d, "t", "y", "group")
  calls <- 0L
  original <- screen_ts_diagnose
  local_mocked_bindings(screen_ts_diagnose = function(...) {
    calls <<- calls + 1L
    original(...)
  })
  shiny::testServer(screen_ts_server(p, "t", "y"), {
    session$setInputs(prev = 0, next_btn = 0, flag_btn = 0, diagnostics = character())
    session$setInputs(flag_btn = 1)
    session$setInputs(scope_1 = c("2", "3"))
    expect_equal(scoped_indices(), c(2L, 3L))
    expect_equal(current_key()$group, "b")
    expect_equal(output$counter, "1 / 2")
    expect_equal(flagged_keys()$group, "a")
    session$setInputs(next_btn = 1)
    expect_equal(current_key()$group, "c")
    session$setInputs(time_scope = c(4, 8))
    expect_equal(current_data()$t, 4:8)
    expect_equal(calls, 0L)
    session$setInputs(diagnostics = "summary")
    expect_equal(diagnostics()$n, 5)
    expect_equal(diagnostics()$mean, mean(d$y[d$group == "c" & d$t %in% 4:8]))
    session$setInputs(time_scope = c(1, 12))
    expect_equal(diagnostics()$n, 12)
    expect_equal(calls, 2L)
    session$setInputs(time_scope = c(4, 8))
    expect_equal(diagnostics()$n, 5)
    expect_equal(calls, 2L)
    session$setInputs(scope_1 = "99")
    expect_length(scoped_indices(), 0)
    expect_equal(output$counter, "0 / 0")
    expect_error(output$plot, "No groups match")
    expect_match(output$plot_title, "No groups")
    session$setInputs(flag_btn = 2, next_btn = 2)
    expect_equal(flagged_keys()$group, "a")
    session$setInputs(scope_1 = character(), time_scope = c(1, 12))
    expect_length(scoped_indices(), 3)
    expect_equal(flagged_keys()$group, "a")
    expect_equal(nrow(current_data()), 12)
  })
})

test_that("time scope preserves unknown times in the full view and filters dates inclusively", {
  d <- data.frame(t = as.Date(c("2020-01-01", "2020-02-01", "2020-03-01", NA)), y = 1:4, g = "a")
  p <- screen_ts_prepare(d, "t", "y", "g")
  time <- screen_ts_time_scope(p$data$t)
  expect_true(time$enabled)
  expect_equal(screen_ts_scope_rows(p, time, time$bounds), p$rows)
  rows <- screen_ts_scope_rows(p, time, as.Date(c("2020-02-01", "2020-03-01")))
  expect_equal(p$data$t[rows[[1]]], as.Date(c("2020-02-01", "2020-03-01")))
  expect_length(screen_ts_scope_rows(p, time, c(NA, 1))[[1]], 0)
  expect_false(screen_ts_time_scope(rep(as.Date("2020-01-01"), 3))$enabled)
  expect_false(screen_ts_time_scope(c(NA_real_, Inf))$enabled)
  instant <- as.POSIXct("2020-01-01 12:00:00", tz = "UTC") + 0:3 * 3600
  p <- screen_ts_prepare(data.frame(t = instant, y = 1:4, g = "a"), "t", "y", "g")
  rows <- screen_ts_scope_rows(p, screen_ts_time_scope(instant), instant[c(2, 3)])
  expect_equal(rows[[1]], 2:3)
})

test_that("group filters combine dimensions and sparse resolution stays inside scope", {
  d <- data.frame(t = 1:4, y = 1:4, a = c("x", "x", "y", "y"), b = c("m", "n", "m", "n"))
  p <- screen_ts_prepare(d, "t", "y", c("a", "b"))
  expect_equal(screen_ts_scope_indices(p, list(c("1", "2"), "2")), c(2L, 4L))
  expect_equal(screen_ts_scope_indices(p, list("2", "2")), 4L)
  expect_true(is.na(screen_ts_resolve(p, list("1", "1"), 4L, allowed = 4L)))
  expect_equal(screen_ts_resolve(p, list("2", "2"), 2L, allowed = 4L), 4L)
})

test_that("changing time scope reselects an available series", {
  skip_if_not_installed("shiny")
  skip_if_not_installed("plotly")
  d <- data.frame(t = 1:12, y = 1:12, g = "one", line = rep(c("a", "b"), each = 6))
  p <- screen_ts_prepare(d, "t", "y", "g", "line")
  shiny::testServer(screen_ts_server(p, "t", "y", "line"), {
    session$setInputs(diagnostics = "summary", diagnostic_series = "1")
    expect_equal(diagnostics()$n, 6)
    session$setInputs(time_scope = c(7, 12))
    expect_equal(selected_series(), 2L)
    expect_equal(diagnostics()$mean, 9.5)
  })
})
